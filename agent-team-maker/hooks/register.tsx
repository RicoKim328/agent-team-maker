import type { EngineInterface, Register } from 'claude-code'

import type { AgentKind, AgentNode, Flow } from '../types'

const PLUGIN = 'agent-team-maker'
const PANE = 'agent-team-maker'
const MARK = '<!-- generated by agent-team-maker -->'
// files exported before the rename carry the old mark and are still ours to overwrite
const OLD_MARK = '<!-- generated by agentteam-maker -->'
const MODELS = ['inherit', 'opus', 'sonnet', 'haiku', 'fable']
const TEAM_COLORS = ['permission', 'suggestion', 'success', 'warning', 'merged', 'ide'] as const

const nodes = atom({ plugin: 'agent-team-maker', key: 'nodes' } as const, [])
const selected = atom({ plugin: 'agent-team-maker', key: 'selected' } as const, null)
const notice = atom({ plugin: 'agent-team-maker', key: 'notice' } as const, '')
const isTeamOn = atom({ plugin: 'agent-team-maker', key: 'isTeamOn' } as const, false)
const announced = atom({ plugin: 'agent-team-maker', key: 'announced' } as const, '')

const newId = () => Math.random().toString(36).slice(2, 10)

const blank = (kind: AgentKind, parentId: string | null, name: string, teamName = ''): AgentNode => ({
  id: newId(),
  parentId,
  kind,
  teamName,
  isActive: true,
  name,
  model: kind === 'agent' ? 'sonnet' : 'inherit',
  role: '',
  useSkills: false,
  skills: [],
  sendsTo: [],
})

const MAIN: AgentNode = { ...blank('main', null, 'main'), id: 'main' }

const starter = (): AgentNode[] => {
  const t1 = { ...blank('team', 'main', 'manager-1', 'Team 1'), model: 'opus', role: 'Reviews and merges the results of members A and B' }
  const t2 = { ...blank('team', 'main', 'manager-2', 'Team 2'), model: 'opus', role: 'Reviews and merges the results of members C and D' }
  return [
    MAIN,
    t1,
    blank('agent', t1.id, 'agent-a'),
    blank('agent', t1.id, 'agent-b'),
    t2,
    blank('agent', t2.id, 'agent-c'),
    blank('agent', t2.id, 'agent-d'),
  ]
}

// Designs saved before teams existed: each old root becomes a team under main.
const normalize = (raw: unknown): AgentNode[] => {
  if (!Array.isArray(raw) || raw.length === 0) return starter()
  const list = raw as Partial<AgentNode>[]
  if (list.some(n => n.kind === 'main')) return list.map(n => ({ ...n, sendsTo: n.sendsTo ?? [] }) as AgentNode)
  let teams = 0
  return [
    MAIN,
    ...list.map(n => {
      const isRoot = n.parentId === null
      if (isRoot) teams += 1
      return {
        ...blank(isRoot ? 'team' : 'agent', null, n.name ?? 'agent'),
        ...n,
        kind: isRoot ? ('team' as const) : ('agent' as const),
        parentId: isRoot ? 'main' : (n.parentId ?? 'main'),
        teamName: isRoot ? `Team ${teams}` : '',
        isActive: true,
      }
    }),
  ]
}

const childrenOf = (list: AgentNode[], id: string | null) => list.filter(n => n.parentId === id)

const teamOf = (list: AgentNode[], node: AgentNode): AgentNode | undefined => {
  let at: AgentNode | undefined = node
  while (at && at.kind !== 'team') at = list.find(n => n.id === at?.parentId)
  return at
}

const kindLabel = (list: AgentNode[], node: AgentNode) => {
  if (node.kind === 'main') return 'Top Orchestrator'
  if (node.kind === 'team') return 'Manager'
  return childrenOf(list, node.id).length > 0 ? 'Orchestrator' : 'Worker'
}

const ordered = (list: AgentNode[]) => {
  const rows: { node: AgentNode; depth: number }[] = []
  const walk = (parentId: string | null, depth: number) => {
    for (const node of childrenOf(list, parentId)) {
      rows.push({ node, depth })
      walk(node.id, depth + 1)
    }
  }
  walk(null, 0)
  return rows
}

const descendants = (list: AgentNode[], id: string): Set<string> => {
  const found = new Set([id])
  // a node may sit before its parent in the array after moves, so walk until stable
  let size = 0
  while (size !== found.size) {
    size = found.size
    for (const node of list) {
      if (node.parentId !== null && found.has(node.parentId)) found.add(node.id)
    }
  }
  return found
}

const slug = (name: string, fallback: string) => {
  const s = name.trim().toLowerCase().replace(/[^a-z0-9-]+/g, '-').replace(/^-+|-+$/g, '')
  return /[a-z]/.test(s) ? s : `${fallback}${s ? `-${s}` : ''}`
}

// The agent type's own name: team-scoped, so two teams may both have an "agent-a".
const typeName = (list: AgentNode[], node: AgentNode) => {
  const team = teamOf(list, node)
  return `${slug(team?.teamName ?? '', 'team')}-${slug(node.name, 'agent')}`
}

// Information flow between agents on one level: main relays a sender's
// result into a receiver's prompt, only along these directions.

const siblingsOf = (list: AgentNode[], node: AgentNode) =>
  node.kind === 'agent' ? childrenOf(list, node.parentId).filter(n => n.kind === 'agent' && n.id !== node.id) : []

const flowOf = (a: AgentNode, b: AgentNode): Flow => {
  const out = a.sendsTo.includes(b.id)
  const back = b.sendsTo.includes(a.id)
  return out && back ? 'both' : out ? 'to' : back ? 'from' : 'none'
}

const setFlow = (list: AgentNode[], aId: string, bId: string, flow: Flow) => {
  const link = (n: AgentNode, other: string, isOn: boolean) => ({
    ...n,
    sendsTo: isOn ? [...n.sendsTo.filter(id => id !== other), other] : n.sendsTo.filter(id => id !== other),
  })
  return list.map(n =>
    n.id === aId ? link(n, bId, flow === 'to' || flow === 'both') : n.id === bId ? link(n, aId, flow === 'from' || flow === 'both') : n,
  )
}

const FLOW_MARK: Record<Flow, string> = { none: '', to: '→', from: '←', both: '↔' }

// `a → b` and `a ↔ b` lines for the given nodes, each pair once.
const flowLines = (list: AgentNode[], group: AgentNode[], prefix: string) => {
  const name = (n: AgentNode) => `\`${prefix}${typeName(list, n)}\``
  return group.flatMap(a =>
    siblingsOf(list, a)
      .filter(b => {
        const flow = flowOf(a, b)
        return flow === 'to' || (flow === 'both' && list.indexOf(a) < list.indexOf(b))
      })
      .map(b => `- ${name(a)} ${FLOW_MARK[flowOf(a, b)]} ${name(b)}`),
  )
}

const firstLine = (text: string) => text.trim().split('\n')[0] ?? ''

const firstOf = (list: AgentNode[]) => list.find(n => n.kind === 'team') ?? list[0]

// The team agents the main session may call right now.
const liveNodes = (list: AgentNode[], isOn: boolean) =>
  isOn ? list.filter(n => n.kind !== 'main' && teamOf(list, n)?.isActive === true) : []

// Tree edits on the flat list: sibling order is array order.

const moveSibling = (list: AgentNode[], id: string, step: -1 | 1) => {
  const node = list.find(n => n.id === id)
  if (!node || node.kind === 'main') return list
  const sibs = childrenOf(list, node.parentId)
  const other = sibs[sibs.indexOf(node) + step]
  if (!other) return list
  const next = [...list]
  next[next.indexOf(node)] = other
  next[list.indexOf(other)] = node
  return next
}

const indent = (list: AgentNode[], id: string) => {
  const node = list.find(n => n.id === id)
  if (!node || node.kind !== 'agent') return list
  const sibs = childrenOf(list, node.parentId)
  const prev = sibs[sibs.indexOf(node) - 1]
  if (!prev || prev.kind !== 'agent') return list
  return [...list.filter(n => n.id !== id), { ...node, parentId: prev.id }]
}

const outdent = (list: AgentNode[], id: string) => {
  const node = list.find(n => n.id === id)
  const parent = node && list.find(n => n.id === node.parentId)
  if (!node || node.kind !== 'agent' || !parent || parent.kind !== 'agent') return list
  const rest = list.filter(n => n.id !== id)
  const at = rest.indexOf(parent) + 1
  return [...rest.slice(0, at), { ...node, parentId: parent.parentId }, ...rest.slice(at)]
}

const insertAfter = (list: AgentNode[], afterId: string | null, node: AgentNode) => {
  const at = afterId === null ? list.length : list.findIndex(n => n.id === afterId) + 1
  return [...list.slice(0, at), node, ...list.slice(at)]
}

const patch = (list: AgentNode[], id: string, fields: Partial<AgentNode>) =>
  list.map(n => (n.id === id ? { ...n, ...fields } : n))

const newTeam = (list: AgentNode[]) => {
  const count = list.filter(n => n.kind === 'team').length + 1
  return { ...blank('team', 'main', `manager-${count}`, `Team ${count}`), model: 'opus' }
}

// Prompts. `prefix` is what the Agent tool's subagent_type starts with:
// the plugin's own types in a session, plain names in exported files.

const agentPrompt = (list: AgentNode[], node: AgentNode, prefix: string) => {
  const team = teamOf(list, node)
  const teamName = team?.teamName ?? ''
  const kids = childrenOf(list, node.id)
  const parent = list.find(n => n.id === node.parentId)
  const lines = [
    `# ${node.name} — ${teamName} ${kindLabel(list, node)}`,
    '',
    '## Role',
    node.role.trim() || '(no role set)',
    '',
    '## Team rules',
    `- You belong to team "${teamName}". You do not need other teams' plans, results or opinions, and you do not use them even if you receive them.`,
    '- Never call other agents yourself. Only the top-level main (the terminal session) calls agents.',
  ]
  if (kids.length > 0) {
    lines.push(
      '',
      '## Sub-agents',
      ...kids.map(k => `- \`${prefix}${typeName(list, k)}\` (${kindLabel(list, k)}): ${firstLine(k.role) || '(no role set)'}`),
      '',
      '## How you work',
      'When a request starts with `[PLAN]`: split the work across your sub-agents and answer only in this format.',
      '```',
      '[DELEGATE]',
      '- to: <subagent_type>',
      '  task: <a concrete instruction that agent can carry out as is>',
      '```',
      'When a request starts with `[MERGE]`: review and merge the sub-agent results passed along with it into a final result.',
      'If the results fall short, ask for more work with a `[REDELEGATE]` block in the same format.',
    )
    const flows = flowLines(list, kids, prefix)
    if (flows.length > 0) {
      lines.push(
        '',
        '## Information flow between your sub-agents',
        ...flows,
        'A result may reach a fellow sub-agent only along these directions (`↔` both ways). In a `[DELEGATE]` list, put a sender before its receiver.',
      )
    }
  } else if (parent) {
    lines.push('', '## Reporting', `Return your result to main, which called you. Main uses it for ${parent.kind === 'main' ? 'the final synthesis' : `the merge by ${parent.name} above you`}, so keep it concise and verifiable.`)
  }
  const sibs = siblingsOf(list, node)
  const name = (n: AgentNode) => `\`${prefix}${typeName(list, n)}\``
  const by = (flow: Flow) => sibs.filter(s => flowOf(node, s) === flow).map(name).join(', ')
  const flowRules = [
    by('from') && `- You may receive results from ${by('from')}, passed by main in \`[FROM <agent>]\` blocks.`,
    by('to') && `- Your result may be passed on to ${by('to')}, so state it so they can build on it.`,
    by('both') && `- You and ${by('both')} exchange results both ways through main, in \`[FROM <agent>]\` blocks.`,
  ].filter(Boolean)
  if (flowRules.length > 0) {
    lines.push('', '## Information flow (same level)', ...flowRules, '- Work of other agents on your level is not shared with you.')
  }
  return lines.join('\n')
}

const mainSection = (list: AgentNode[], live: AgentNode[], prefix: string) => {
  const isLive = new Set(live.map(n => n.id))
  const main = list.find(n => n.kind === 'main')
  const tree = ordered(list)
    .filter(r => isLive.has(r.node.id))
    .map(({ node, depth }) => {
      const head = node.kind === 'team' ? `Team "${node.teamName}" — manager ` : ''
      const skills = node.useSkills && node.skills.length > 0 ? `, skills: ${node.skills.join(', ')}` : ''
      return `${'  '.repeat(depth - 1)}- ${head}\`${prefix}${typeName(list, node)}\` (${kindLabel(list, node)}, ${node.model}${skills}): ${firstLine(node.role) || '-'}`
    })
  const flows = flowLines(list, live, prefix)
  return [
    '# Agent Team (agent-team-maker)',
    'You (Claude in this terminal) are the top Orchestrator of this agent team. Only you call sub-agents, with the Agent tool.',
    ...(main && main.role.trim() ? ['', '## Top-level instructions', main.role.trim()] : []),
    '',
    '## Teams (subagent_type)',
    ...tree,
    '',
    '## Procedure',
    'When a task comes in, split it by each team\'s role, then for each team independently:',
    '1. Call the team manager with a prompt that starts with `[PLAN]` and holds only that team\'s share of the work. → You get a `[DELEGATE]` list.',
    '2. Call each sub-agent on the list (in parallel when independent). If a sub-agent is an Orchestrator, apply steps 1-3 to it the same way.' +
      (flows.length > 0 ? ' Along an information flow below, call the sender first and put its result in the receiver\'s prompt as `[FROM <subagent_type>] … [/FROM]`.' : ''),
    '3. Collect the results and call the manager again with a prompt that starts with `[MERGE]` and holds only that team\'s results. On `[REDELEGATE]`, go back to step 2.',
    '4. Synthesize all teams\' results yourself and answer the user.',
    '',
    '## Team isolation rules (always follow)',
    '- A prompt to one team\'s agent never contains another team\'s plans, results, outputs or opinions.',
    '- Only you compare or combine teams, in step 4. Teams never exchange opinions.',
    '- Team agents cannot call other agents (the mod blocks it).',
    '- Simple questions, or work no team\'s role covers, you may handle directly without the teams.',
    ...(flows.length > 0
      ? [
          '',
          '## Information flow within a level (always follow)',
          ...flows,
          '- `→` lets you pass the left agent\'s result to the right one only; `↔` both ways, for as many rounds as the work needs.',
          '- Pass a result to an agent on the same level only along these directions, inside a `[FROM <subagent_type>]` block (the mod blocks any other). Agents on one level with no flow between them never see each other\'s results.',
        ]
      : []),
  ].join('\n')
}

const agentSpec = (list: AgentNode[], node: AgentNode) => ({
  name: typeName(list, node),
  description: `[${teamOf(list, node)?.teamName ?? ''}] ${firstLine(node.role) || kindLabel(list, node)}`,
  prompt: agentPrompt(list, node, `${PLUGIN}:`),
  ...(node.model !== 'inherit' ? { model: node.model } : {}),
  ...(node.useSkills && node.skills.length > 0 ? { skills: node.skills } : {}),
})

const duplicateName = (list: AgentNode[]) => {
  const names = list.filter(n => n.kind !== 'main').map(n => typeName(list, n))
  return names.find((s, i) => names.indexOf(s) !== i)
}

// Registers the live team agents as this plugin's agent types; stale names
// from renames stay registered but `agent.offer` hides them.
const syncAgents = async ($: EngineInterface) => {
  const list = await read($, nodes)
  const live = liveNodes(list, await read($, isTeamOn))
  const dup = duplicateName(live)
  if (dup) return `Duplicate name: "${dup}" — rename one of them within the team.`
  for (const node of live) await $.agent.register(agentSpec(list, node))
  return ''
}

const change = async ($: EngineInterface, fn: (list: AgentNode[]) => AgentNode[]) => {
  const list = await update($, nodes, fn)
  await $.store.set('design', list)
  if (await read($, isTeamOn)) {
    const problem = await syncAgents($).catch((error: unknown) => `Agent registration failed: ${String(error)}`)
    await update($, notice, () => problem)
  }
  return list
}

const setTeamOn = async ($: EngineInterface, isOn: boolean) => {
  await update($, isTeamOn, () => isOn)
  await $.store.set('teamOn', isOn)
  const problem = isOn ? await syncAgents($).catch((error: unknown) => `Agent registration failed: ${String(error)}`) : ''
  await update($, notice, () =>
    problem || (isOn ? 'Teams on: from the next request, Claude in this terminal runs the teams as top Orchestrator.' : 'Teams off: back to plain Claude.'),
  )
}

const announce = async ($: EngineInterface) => {
  const list = await read($, nodes)
  const live = liveNodes(list, await read($, isTeamOn))
  const text = live.length > 0 ? mainSection(list, live, `${PLUGIN}:`) : ''
  const last = await read($, announced)
  if (text === last) return
  const note =
    text !== ''
      ? `<agent-team-maker>\nThese instructions replace all earlier agent-team-maker instructions.\n\n${text}\n</agent-team-maker>`
      : '<agent-team-maker>\nTeams are switched off. Stop following the earlier agent-team-maker team instructions and work directly as usual.\n</agent-team-maker>'
  if (text === '' && last === '') return
  await $.session.append({ message: { type: 'user', content: [{ type: 'text', text: note }] } })
  await update($, announced, () => text)
}

// The model's own way to add a team, so main can build one when asked.
const ADD_TEAM = 'add_team'
const MEMBER_SCHEMA = {
  type: 'object',
  properties: {
    name: { type: 'string', description: 'Agent name (lowercase letters, digits and hyphens recommended)' },
    model: { type: 'string', enum: MODELS },
    role: { type: 'string', description: 'What this agent is responsible for' },
    skills: { type: 'array', items: { type: 'string' } },
    sendsTo: {
      type: 'array',
      items: { type: 'string' },
      description: 'Members only: names of fellow members this member\'s results may be passed to (one way; list each other for both ways)',
    },
  },
  required: ['name', 'role'],
}

type MemberInput = { name: string; model?: string; role: string; skills?: string[]; sendsTo?: string[] }

const toNode = (kind: AgentKind, parentId: string, m: MemberInput, teamName = ''): AgentNode => ({
  ...blank(kind, parentId, m.name, teamName),
  ...(m.model && MODELS.includes(m.model) ? { model: m.model } : {}),
  role: m.role,
  useSkills: (m.skills ?? []).length > 0,
  skills: m.skills ?? [],
})

// Why main may not pass a `[FROM <agent>]` block into this prompt, or ''.
const flowProblem = (list: AgentNode[], receiver: AgentNode, prompt: string) => {
  const byType = (t: string) => list.find(n => n.kind !== 'main' && typeName(list, n) === t.replace(`${PLUGIN}:`, ''))
  for (const [, type] of prompt.matchAll(/\[FROM\s+([^\]\s]+)\]/g)) {
    const sender = byType(type ?? '')
    if (!sender || sender.id === receiver.id) continue
    if (teamOf(list, sender) !== teamOf(list, receiver)) {
      return `"${sender.name}" is in another team, and teams never see each other's results. Remove that [FROM] block.`
    }
    if (siblingsOf(list, receiver).includes(sender) && !sender.sendsTo.includes(receiver.id)) {
      const allowed = siblingsOf(list, receiver).filter(s => s.sendsTo.includes(receiver.id)).map(s => s.name)
      return `"${sender.name}" may not pass its result to "${receiver.name}" (information flow). ${
        allowed.length > 0 ? `It may receive only from: ${allowed.join(', ')}.` : 'It receives from no agent on its level.'
      } Remove that [FROM] block.`
    }
  }
  return ''
}

// Export: one subagent file per team agent plus a team overview.

const agentFile = (list: AgentNode[], node: AgentNode) => {
  const spec = agentSpec(list, node)
  return [
    '---',
    `name: ${spec.name}`,
    `description: ${JSON.stringify(spec.description)}`,
    ...(spec.model ? [`model: ${spec.model}`] : []),
    ...(spec.skills ? [`skills: ${spec.skills.join(', ')}`] : []),
    '---',
    MARK,
    agentPrompt(list, node, ''),
    '',
  ].join('\n')
}

const exportTeam = async ($: EngineInterface, list: AgentNode[]) => {
  const dup = duplicateName(list)
  if (dup) return `Duplicate name: "${dup}" — fix the name and export again.`

  const written: string[] = []
  const skipped: string[] = []
  for (const node of list.filter(n => n.kind !== 'main')) {
    const path = `.claude/agents/${typeName(list, node)}.md`
    if (await $.fs.exists(path)) {
      const old = await $.fs.read(path)
      if (!old.includes(MARK) && !old.includes(OLD_MARK)) {
        skipped.push(path)
        continue
      }
    }
    await $.fs.write(path, agentFile(list, node))
    written.push(path)
  }
  const all = list.filter(n => n.kind !== 'main')
  await $.fs.write('.claude/agentteam/TEAM.md', [MARK, mainSection(list, all, ''), ''].join('\n'))
  await $.fs.write('.claude/agentteam/team.json', JSON.stringify(list, null, 2) + '\n')

  const kept = skipped.length > 0 ? ` · skipped hand-written files: ${skipped.join(', ')}` : ''
  return `Exported ${written.length} → .claude/agents/, overview → .claude/agentteam/TEAM.md${kept}`
}

export const register: Register = on => {
  on('session.start', async ($, e, next) => {
    await $.command.register({
      name: 'agent-team-maker',
      description: 'Open the panel to design team-based Orchestrator/Worker agent hierarchies and switch them on or off',
    })
    await $.tool.register({
      name: ADD_TEAM,
      description:
        'Add a new team to the agent-team-maker panel: a team name, one manager and one or more members. Use only when the user asks for a team.',
      isDeferred: false,
      inputSchema: {
        type: 'object',
        properties: {
          teamName: { type: 'string', description: 'Team name (distinct from other teams)' },
          manager: MEMBER_SCHEMA,
          members: { type: 'array', items: MEMBER_SCHEMA, minItems: 1 },
        },
        required: ['teamName', 'manager', 'members'],
      },
    })
    const current = await read($, nodes)
    if (!current.some(n => n.kind === 'main')) {
      const list = normalize(current.length > 0 ? current : await $.store.get('design'))
      await update($, nodes, () => list)
      await update($, selected, () => firstOf(list)?.id ?? null)
      await $.store.set('design', list)
      const savedOn = await $.store.get('teamOn')
      await update($, isTeamOn, () => savedOn === true)
    } else if (current.some(n => n.sendsTo === undefined)) {
      await update($, nodes, normalize)
    }
    if (await read($, isTeamOn)) {
      const problem = await syncAgents($).catch((error: unknown) => `Agent registration failed: ${String(error)}`)
      await update($, notice, () => problem)
    }
    return next(e)
  })

  on('tool.call', { tool: 'mcp__agent-team-maker__add_team' }, async ($, e) => {
    const input = e as unknown as { teamName: string; manager: MemberInput; members: MemberInput[] }
    const manager = toNode('team', 'main', input.manager, input.teamName)
    const made = input.members.map(m => toNode('agent', manager.id, m))
    const members = made.map((n, i) => ({
      ...n,
      sendsTo: (input.members[i]?.sendsTo ?? []).flatMap(to => made.filter(o => o.name === to && o.id !== n.id).map(o => o.id)),
    }))
    const list = await change($, l => [...l, manager, ...members])
    await update($, selected, () => manager.id)
    const problem = await read($, notice)
    const names = [manager, ...members].map(n => `${PLUGIN}:${typeName(list, n)}`)
    return {
      result: [
        `Added team "${input.teamName}" (1 manager, ${members.length} members).`,
        (await read($, isTeamOn)) ? `Agent types: ${names.join(', ')}` : 'The teams switch is off, so they cannot be called yet.',
        problem,
      ].filter(Boolean).join('\n'),
    }
  })

  on('command.run', { command: 'agent-team-maker' }, async $ => {
    await $.ui.open({ id: PANE, title: 'Agent Team Maker', focus: true })
    return { text: 'Opened the Agent Team Maker panel.' }
  })

  // The main session reads its team as a note in the conversation, sent again
  // only when the team or the switch changed since the last one.
  on('prompt.submit', async ($, e, next) => {
    await announce($).catch(() => undefined)
    return next(e)
  })

  // A /clear empties the conversation, the note with it.
  on('session.end', async ($, e, next) => {
    if (e.reason === 'clear') await update($, announced, () => '')
    return next(e)
  })

  // Only the live team agents are offered; renamed or switched-off ones are hidden.
  on('agent.offer', async ($, e, next) => {
    if (!e.agent.startsWith(`${PLUGIN}:`)) return next(e)
    const list = await read($, nodes)
    const live = liveNodes(list, await read($, isTeamOn))
    const isLive = live.some(n => `${PLUGIN}:${typeName(list, n)}` === e.agent)
    return isLive ? next(e) : { isOffered: false }
  }).catch(($, e, next) => (next.called || !e.agent.startsWith(`${PLUGIN}:`) ? next(e) : { isOffered: false }))

  // Team agents are called by the main session alone, never by one another,
  // and main relays results between agents of one level only along their flows.
  on('agent.spawn', async ($, e, next) => {
    if (e.subagentType.startsWith(`${PLUGIN}:`) && e.parentAgentId !== undefined) {
      return { deny: 'Team agents can be called only by the top-level main (the terminal session). Return your result to main.' }
    }
    if (e.subagentType.startsWith(`${PLUGIN}:`)) {
      const list = await read($, nodes)
      const receiver = list.find(n => n.kind !== 'main' && `${PLUGIN}:${typeName(list, n)}` === e.subagentType)
      const problem = receiver ? flowProblem(list, receiver, e.prompt) : ''
      if (problem) return { deny: problem }
    }
    return next(e)
  }).catch(($, e, next) => (next.called ? next(e) : { deny: 'agent-team-maker: spawn check failed' }))

  on('ui.render', { component: 'Pane', requestId: PANE }, async ($, e) => {
    if (e.surface === 'mobile') {
      const { Text } = $.ui.resolve(e)
      return <Text dimColor>Agent Team Maker can be edited in the terminal or desktop app.</Text>
    }
    const { Box, Text, Button, Input, Select } = $.ui.resolve(e)
    const list = await read($, nodes)
    const selId = await read($, selected)
    const message = await read($, notice)
    const isOn = await read($, isTeamOn)
    const node = list.find(n => n.id === selId)
    const isWide = e.props.bodyColumns >= 110
    const teams = list.filter(n => n.kind === 'team')
    const colorOf = (n: AgentNode) => {
      const team = teamOf(list, n)
      return team ? (TEAM_COLORS[teams.indexOf(team) % TEAM_COLORS.length] ?? 'subtle') : 'claude'
    }

    const act = (fn: (list: AgentNode[], id: string) => AgentNode[]) => () => {
      if (node) void change($, l => fn(l, node.id))
    }

    const add = async (fresh: AgentNode, afterId: string | null) => {
      await change($, l => insertAfter(l, afterId, fresh))
      await update($, selected, () => fresh.id)
    }

    const addChild = () => {
      if (!node) return
      if (node.kind === 'main') return add(newTeam(list), null)
      return add(blank('agent', node.id, `agent-${list.length}`), null)
    }

    const addSibling = () => {
      if (!node || node.kind === 'main') return
      if (node.kind === 'team') return add(newTeam(list), lastOfSubtree(node.id))
      return add(blank('agent', node.parentId, `agent-${list.length}`), lastOfSubtree(node.id))
    }

    // the new box goes after the whole subtree, so array order still reads as the tree
    const lastOfSubtree = (id: string) => {
      const inside = descendants(list, id)
      return [...list].reverse().find(n => inside.has(n.id))?.id ?? id
    }

    const remove = async () => {
      if (!node || node.kind === 'main') return
      const gone = descendants(list, node.id)
      await change($, l => l.filter(n => !gone.has(n.id)))
      await update($, selected, () => node.parentId)
    }

    const runExport = async () => {
      const text = await exportTeam($, await read($, nodes))
      await update($, notice, () => text)
    }

    const tree = (
      <Box flexDirection="column" flexGrow={1}>
        <Text weight="bold">Team structure</Text>
        {ordered(list).map(({ node: n, depth }) => {
          const isSel = n.id === selId
          const team = teamOf(list, n)
          const flows = siblingsOf(list, n)
            .filter(b => flowOf(n, b) !== 'none')
            .map(b => `${FLOW_MARK[flowOf(n, b)]} ${b.name}`)
          const isDim = n.kind !== 'main' && (!isOn || team?.isActive !== true)
          const title =
            n.kind === 'main'
              ? '◆ main · Claude in this terminal'
              : n.kind === 'team'
                ? `▣ ${n.teamName}${n.isActive ? '' : ' (off)'}`
                : `${childrenOf(list, n.id).length > 0 ? '◆' : '○'} ${n.name}`
          const sub =
            n.kind === 'main'
              ? `${kindLabel(list, n)} · ${isOn ? 'teams running' : 'teams off'}`
              : n.kind === 'team'
                ? `manager ${n.name} · ${n.model}`
                : `${kindLabel(list, n)} · ${n.model}`
          return (
            <Box key={`row-${n.id}`} flexDirection="row">
              {depth > 0 && <Text dimColor>{'    '.repeat(depth - 1) + ' └─ '}</Text>}
              <Box
                key={`box-${n.id}`}
                flexDirection="column"
                borderStyle={isSel ? 'double' : n.kind === 'agent' ? 'round' : 'bold'}
                borderColor={isSel ? 'claude' : colorOf(n)}
                borderDimColor={isDim && !isSel}
                paddingX={1}
              >
                <Button key={`pick-${n.id}`} plain dimColor={isDim} onPress={() => update($, selected, () => n.id)}>
                  {title} <Text dimColor>· {sub}</Text>
                </Button>
                {n.role.trim() !== '' && <Text dimColor>{firstLine(n.role).slice(0, 60)}</Text>}
                {flows.length > 0 && <Text color="permission">{flows.join(' · ')}</Text>}
                {n.useSkills && (
                  <Text color="suggestion">
                    skills: {n.skills.length > 0 ? n.skills.join(', ') : '(add some)'}
                  </Text>
                )}
              </Box>
            </Box>
          )
        })}
      </Box>
    )

    const controls = (
      <Box flexDirection="column">
        <Box flexDirection="row" columnGap={1}>
          <Button key="team-on" hotkey="t" variant={isOn ? 'primary' : 'secondary'} onPress={() => setTeamOn($, !isOn)}>
            {isOn ? '● Teams: on' : '○ Teams: off'}
          </Button>
          <Text dimColor>{isOn ? `${teams.filter(t => t.isActive).length} team(s) running` : 'Turn on to let Claude in this terminal run the teams'}</Text>
        </Box>
        <Box flexDirection="row" flexWrap="wrap" columnGap={1}>
          <Button key="up" hotkey="k" onPress={act((l, id) => moveSibling(l, id, -1))}>↑ Up</Button>
          <Button key="down" hotkey="j" onPress={act((l, id) => moveSibling(l, id, 1))}>↓ Down</Button>
          <Button key="out" hotkey="h" onPress={act(outdent)}>← Level up</Button>
          <Button key="in" hotkey="l" onPress={act(indent)}>→ Level down</Button>
        </Box>
        <Box flexDirection="row" flexWrap="wrap" columnGap={1}>
          <Button key="add-team" hotkey="n" onPress={() => add(newTeam(list), null)}>+ Team</Button>
          <Button key="add-child" hotkey="a" onPress={addChild}>+ Child</Button>
          <Button key="add-sib" hotkey="s" onPress={addSibling}>+ Sibling</Button>
          <Button key="del" hotkey="x" onPress={remove}>Delete</Button>
          <Button key="export" hotkey="e" onPress={runExport}>Export files</Button>
        </Box>
        <Text dimColor>Keys (panel focused): t teams on/off · k/j up/down · h/l level · n team · a/s add · x delete · e export</Text>
        {message !== '' && <Text color="success">{message}</Text>}
      </Box>
    )

    const agentFields = (n: AgentNode) => (
      <Box flexDirection="column">
        <Input
          key={`name-${n.id}`}
          label={n.kind === 'team' ? 'Manager name' : 'Name'}
          value={n.name}
          onInput={v => change($, l => patch(l, n.id, { name: v }))}
          onSubmit={v => change($, l => patch(l, n.id, { name: v }))}
        />
        <Select
          key={`model-${n.id}`}
          label="Model"
          value={n.model}
          options={MODELS.map(m => ({ value: m }))}
          onSelect={v => change($, l => patch(l, n.id, { model: v }))}
        />
        <Input
          key={`role-${n.id}`}
          label="Role"
          rows={3}
          placeholder={n.kind === 'team' ? "How to handle the members' results" : 'What this agent is responsible for'}
          value={n.role}
          onInput={v => change($, l => patch(l, n.id, { role: v }))}
          onSubmit={v => change($, l => patch(l, n.id, { role: v }))}
        />
        <Select
          key={`skills-on-${n.id}`}
          label="Skills"
          value={n.useSkills ? 'on' : 'off'}
          options={[
            { value: 'off', label: 'Off' },
            { value: 'on', label: 'On' },
          ]}
          onSelect={v => change($, l => patch(l, n.id, { useSkills: v === 'on' }))}
        />
        {n.useSkills && (
          <Box flexDirection="column">
            <Box flexDirection="row" flexWrap="wrap" columnGap={1}>
              {n.skills.length === 0 && <Text dimColor>No skills yet</Text>}
              {n.skills.map(skill => (
                <Button
                  key={`rm-${n.id}-${skill}`}
                  onPress={() => change($, l => patch(l, n.id, { skills: n.skills.filter(s => s !== skill) }))}
                >
                  {skill} ✕
                </Button>
              ))}
            </Box>
            <Input
              key={`add-skill-${n.id}-${n.skills.length}`}
              label="Add skill"
              placeholder="Skill names (comma-separated)"
              submitLabel="add"
              onSubmit={v => {
                const added = v.split(',').map(s => s.trim()).filter(s => s !== '' && !n.skills.includes(s))
                if (added.length > 0) void change($, l => patch(l, n.id, { skills: [...n.skills, ...added] }))
              }}
            />
          </Box>
        )}
      </Box>
    )

    const flowFields = (n: AgentNode) => {
      const sibs = siblingsOf(list, n)
      return (
        <Box flexDirection="column">
          <Text weight="bold">Information flow (same level)</Text>
          {sibs.length === 0 ? (
            <Text dimColor>No other agents on this level.</Text>
          ) : (
            sibs.map(b => (
              <Select
                key={`flow-${n.id}-${b.id}`}
                label={b.name}
                value={flowOf(n, b)}
                options={[
                  { value: 'none', label: '— no sharing' },
                  { value: 'to', label: `→ sends to ${b.name}` },
                  { value: 'from', label: `← receives from ${b.name}` },
                  { value: 'both', label: `↔ both ways` },
                ]}
                onSelect={v => change($, l => setFlow(l, n.id, b.id, v as Flow))}
              />
            ))
          )}
          <Text dimColor>Main passes results only along these directions; the mod blocks any other.</Text>
        </Box>
      )
    }

    const editor = !node ? (
      <Text dimColor>Select a box to edit it here.</Text>
    ) : node.kind === 'main' ? (
      <Box flexDirection="column" flexGrow={1} borderStyle="single" borderColor="subtle" paddingX={1}>
        <Text weight="bold">main — Claude in this terminal</Text>
        <Text dimColor>The top Orchestrator. It uses this session's model, and every sub-agent call happens here.</Text>
        <Input
          key="role-main"
          label="Top-level instructions"
          rows={3}
          placeholder="How to combine the teams' results, etc. (optional)"
          value={node.role}
          onInput={v => change($, l => patch(l, 'main', { role: v }))}
          onSubmit={v => change($, l => patch(l, 'main', { role: v }))}
        />
      </Box>
    ) : (
      <Box flexDirection="column" flexGrow={1} borderStyle="single" borderColor={colorOf(node)} paddingX={1}>
        {node.kind === 'team' ? (
          <Box flexDirection="column">
            <Text weight="bold">Edit team</Text>
            <Input
              key={`team-name-${node.id}`}
              label="Team name"
              value={node.teamName}
              onInput={v => change($, l => patch(l, node.id, { teamName: v }))}
              onSubmit={v => change($, l => patch(l, node.id, { teamName: v }))}
            />
            <Select
              key={`team-active-${node.id}`}
              label="This team"
              value={node.isActive ? 'on' : 'off'}
              options={[
                { value: 'on', label: 'On' },
                { value: 'off', label: 'Off' },
              ]}
              onSelect={v => change($, l => patch(l, node.id, { isActive: v === 'on' }))}
            />
            <Text weight="bold">Manager</Text>
          </Box>
        ) : (
          <Text weight="bold">
            Edit {kindLabel(list, node)} <Text dimColor>(in {teamOf(list, node)?.teamName} · Orchestrator when it has children)</Text>
          </Text>
        )}
        {agentFields(node)}
        {node.kind === 'agent' && flowFields(node)}
        <Text dimColor>Agent type: {PLUGIN}:{typeName(list, node)}</Text>
      </Box>
    )

    return (
      <Box flexDirection="column" rowGap={1}>
        {controls}
        <Box flexDirection={isWide ? 'row' : 'column'} columnGap={2} rowGap={1}>
          {tree}
          {editor}
        </Box>
      </Box>
    )
  })
}
